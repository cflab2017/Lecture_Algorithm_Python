# 설명  : 주요 Big-O 복잡도 클래스를 실제 연산 횟수로 시각화
# 시간복잡도: 각 함수별 주석 참고
# 공간복잡도: O(1) — 추가 공간 사용 없음
# =============================================================================

import math


# ---------------------------------------------------------------------------
# O(1) — 상수 시간: 입력 크기와 무관하게 항상 같은 횟수의 연산
# ---------------------------------------------------------------------------
def o_constant(arr: list) -> tuple:
    """배열의 첫 번째 원소를 반환합니다. 시간복잡도: O(1)"""
    count = 0
    result = arr[0]  # 단 1번의 접근
    count += 1
    return result, count


# ---------------------------------------------------------------------------
# O(log n) — 로그 시간: 매 단계마다 탐색 범위를 절반으로 줄임
# ---------------------------------------------------------------------------
def o_log_n(n: int) -> int:
    """이진 탐색 방식으로 1에 도달하는 단계 수를 반환합니다. 시간복잡도: O(log n)"""
    count = 0
    current = n
    while current > 1:
        current //= 2  # 절반으로 줄이기
        count += 1
    return count


# ---------------------------------------------------------------------------
# O(n) — 선형 시간: 배열의 모든 원소를 한 번씩 방문
# ---------------------------------------------------------------------------
def o_linear(arr: list) -> tuple:
    """배열의 합을 구합니다. 시간복잡도: O(n)"""
    count = 0
    total = 0
    for x in arr:  # n번 반복
        total += x
        count += 1
    return total, count


# ---------------------------------------------------------------------------
# O(n log n) — 선형로그 시간: 각 원소에 대해 로그 단계 수행
# ---------------------------------------------------------------------------
def o_n_log_n_estimate(n: int) -> int:
    """n log n의 예상 연산 수를 반환합니다. 시간복잡도: O(n log n)"""
    if n <= 1:
        return 1
    return int(n * math.log2(n))


# ---------------------------------------------------------------------------
# O(n²) — 이차 시간: 이중 반복문 (모든 쌍을 탐색)
# ---------------------------------------------------------------------------
def o_quadratic(arr: list) -> tuple:
    """모든 원소 쌍의 합이 0인 경우를 셉니다. 시간복잡도: O(n²)"""
    count = 0
    pairs = 0
    n = len(arr)
    for i in range(n):              # 외부 루프: n번
        for j in range(i + 1, n):  # 내부 루프: n-i-1번
            count += 1
            if arr[i] + arr[j] == 0:
                pairs += 1
    return pairs, count


# ---------------------------------------------------------------------------
# O(2ⁿ) — 지수 시간: 모든 부분집합 열거 (n이 작을 때만 사용 가능)
# ---------------------------------------------------------------------------
def o_exponential(n: int) -> int:
    """n개 원소의 모든 부분집합 수를 반환합니다. 시간복잡도: O(2ⁿ)"""
    count = 0
    for mask in range(1 << n):  # 2^n 가지
        count += 1
    return count


# ---------------------------------------------------------------------------
# 복잡도 성장 비교 표 출력
# ---------------------------------------------------------------------------
def print_complexity_table(n: int) -> None:
    """n이 주어졌을 때 각 복잡도의 연산 수를 테이블로 출력합니다."""
    log_n = int(math.log2(n)) if n > 1 else 1
    n_log_n = int(n * math.log2(n)) if n > 1 else n
    n_sq = n * n
    two_n = 2 ** n if n <= 30 else None

    print(f"\n복잡도 성장 비교 (n={n})")
    print("╔═══════════════╦══════════════════════╗")
    print("║ Big-O         ║ 연산 수 (대략)        ║")
    print("╠═══════════════╬══════════════════════╣")
    print(f"║ O(1)          ║ {1:<20} ║")
    print(f"║ O(log n)      ║ {log_n:<20} ║")
    print(f"║ O(n)          ║ {n:<20} ║")
    print(f"║ O(n log n)    ║ {n_log_n:<20} ║")
    print(f"║ O(n²)         ║ {n_sq:<20} ║")
    if two_n is None:
        print(f"║ O(2ⁿ)         ║ {'너무 큼 (계산 불가)':<20} ║")
    else:
        print(f"║ O(2ⁿ)         ║ {two_n:<20} ║")
    print("╚═══════════════╩══════════════════════╝")


def main():
    print("=" * 55)
    print("  Big-O 복잡도 데모")
    print("=" * 55)

    n = 100_000
    arr_large = list(range(n))

    # O(1) 데모
    _, cnt = o_constant(arr_large)
    print(f"\nO(1)     연산 횟수: {cnt:>12}  (n={n})")

    # O(log n) 데모
    cnt = o_log_n(n)
    print(f"O(log n) 연산 횟수: {cnt:>12}  (n={n})")

    # O(n) 데모
    _, cnt = o_linear(arr_large)
    print(f"O(n)     연산 횟수: {cnt:>12}  (n={n})")

    # O(n log n) 데모 (예상 값)
    cnt = o_n_log_n_estimate(n)
    print(f"O(n logn)연산 횟수: {cnt:>12}  (n={n}, 예상값)")

    # O(n²) — 작은 배열로 실제 측정
    n_small = 1000
    arr_mid = list(range(-n_small // 2, n_small // 2))
    _, cnt = o_quadratic(arr_mid)
    print(f"O(n²)    연산 횟수: {cnt:>12}  (n={n_small})")

    # O(2ⁿ) — 매우 작은 n만 가능
    n_exp = 20
    cnt = o_exponential(n_exp)
    print(f"O(2ⁿ)    연산 횟수: {cnt:>12}  (n={n_exp})")

    # 복잡도 성장 비교 표
    print_complexity_table(16)
    print_complexity_table(1000)
    print_complexity_table(1_000_000)

    print("\n[참고] 시간 제한 1초 ≈ 10^8 연산")
    print("[참고] n=100,000 이면 O(n log n) ≈ 1.7×10^6 → 안전")
    print("[참고] n=100,000 이면 O(n²)      ≈ 10^10  → 시간 초과")


if __name__ == "__main__":
    main()

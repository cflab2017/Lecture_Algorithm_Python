# =============================================================================
# 백준 10989번: 수 정렬하기 3
# 링크: https://www.acmicpc.net/problem/10989
# 시간복잡도: O(n + k) — n개 읽기 + k=10,000 범위 출력 (계수 정렬)
# 공간복잡도: O(k) — 카운터 배열 크기 10,001 (입력 배열 저장 안 함)
#
# 핵심: N=10,000,000, 메모리 제한 8MB
#   - 모든 수를 리스트에 저장하면 MLE → 카운터 배열만 사용
#   - input()으로 1천만 번 읽으면 TLE → sys.stdin 사용
#   - print()로 1천만 번 출력하면 TLE → sys.stdout.write 사용
# =============================================================================

import sys


def solve():
    # -----------------------------------------------------------------------
    # 빠른 입력: sys.stdin.buffer.read()로 한 번에 읽기 (bytes 처리가 더 빠름)
    # input()을 1천만 번 호출하면 TLE 발생
    # -----------------------------------------------------------------------
    data = sys.stdin.buffer.read().split()
    n = int(data[0])

    # -----------------------------------------------------------------------
    # 계수 정렬 (Counting Sort)
    # 값의 범위: 1 ≤ x ≤ 10,000
    # count[v] = v가 등장한 횟수
    # -----------------------------------------------------------------------
    k = 10_001
    count = [0] * k  # O(k) 공간 — 10,001개 정수만 저장

    # 각 숫자의 등장 횟수 카운트 — O(n)
    for i in range(1, n + 1):
        val = int(data[i])
        count[val] += 1

    # -----------------------------------------------------------------------
    # 빠른 출력: 리스트에 모아서 한 번에 출력
    # print()를 1천만 번 호출하면 TLE 발생
    # -----------------------------------------------------------------------
    output = []
    for v in range(1, k):       # 1부터 10,000까지
        if count[v] > 0:
            # v를 count[v]번 출력 (문자열 반복 사용)
            output.append((str(v) + '\n') * count[v])

    sys.stdout.write(''.join(output))


if __name__ == "__main__":
    solve()

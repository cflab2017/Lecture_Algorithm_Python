# 백준 1676번: 팩토리얼 0의 개수
# 링크: https://www.acmicpc.net/problem/1676
# 시간복잡도: O(log₅ N) — 5의 거듭제곱으로 나눔
# 공간복잡도: O(1) — 추가 공간 없음
#
# 자료구조 선택: 특별한 자료구조 불필요 — 순수 수학 계산
#
# 핵심 아이디어:
#   N! 끝의 0 개수 = N!의 소인수 분해에서 2와 5의 쌍의 수
#   2의 개수 > 5의 개수 이므로, 5의 개수만 세면 됩니다.
#
#   5의 개수 = floor(N/5) + floor(N/25) + floor(N/125) + ...
#
#   예: 25! 에서 5의 개수
#     floor(25/5)  = 5   (5, 10, 15, 20, 25 — 각 1개 포함)
#     floor(25/25) = 1   (25 = 5² — 추가로 1개 더)
#     합계 = 6
#
# 왜 N!을 직접 계산하면 안 되는가?
#   N=500이면 N!은 수천 자리 수 → 메모리/시간 문제
# =============================================================================

import sys


def count_trailing_zeros(n: int) -> int:
    """N!의 끝자리 0 개수를 반환합니다.

    시간복잡도: O(log₅ n) — n을 5로 계속 나눔
    공간복잡도: O(1)
    """
    count = 0
    power_of_5 = 5

    while power_of_5 <= n:
        count += n // power_of_5  # 5^k의 배수 개수
        power_of_5 *= 5            # 다음 5의 거듭제곱

    return count


def solve():
    n = int(sys.stdin.readline())
    print(count_trailing_zeros(n))


if __name__ == "__main__":
    solve()
